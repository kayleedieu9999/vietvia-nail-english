const byId = new Map(allGrammarRules.map((rule) => [rule.id, rule]));

export function getGrammarRuleById(id: string): GrammarRuleLesson | undefined {
  return byId.get(id);
}

export function getGrammarRulesByPhase(phaseNumber: number): GrammarRuleLesson[] {
  return allGrammarRules
    .filter((rule) => rule.phaseNumber === phaseNumber)
    .sort((a, b) => a.ruleNumber - b.ruleNumber);
}

/**
 * Metadata only (no whenToUse/pattern/examples/quiz text) — safe to pass
 * into Client Components (the program list and phase-detail pages) without
 * pulling all 100 rules' full teaching content into the browser bundle, same
 * reasoning as `LessonSummary` in `src/types/content.ts`.
 */
export interface GrammarRuleSummary {
  id: string;
  ruleNumber: number;
  phaseNumber: number;
  title: string;
}

function toSummary(rule: GrammarRuleLesson): GrammarRuleSummary {
  return { id: rule.id, ruleNumber: rule.ruleNumber, phaseNumber: rule.phaseNumber, title: rule.title };
}

export function getAllGrammarRuleSummaries(): GrammarRuleSummary[] {
  return allGrammarRules.map(toSummary).sort((a, b) => a.ruleNumber - b.ruleNumber);
}

export function getGrammarRuleSummariesByPhase(phaseNumber: number): GrammarRuleSummary[] {
  return getGrammarRulesByPhase(phaseNumber).map(toSummary);
}

export interface GrammarReviewEntry {
  title: string;
  targetEnglish: string;
  vietnameseHint: string;
}

/**
 * id → title/targetEnglish/vietnameseHint for that rule. Just those 3 short
 * strings per rule (a few KB total), not the full teaching content — safe to
 * ship to a Client Component (the shared `/on-tap` review page and the
 * homepage review card) so they can show the REAL sentence for whichever
 * rules the learner marked/got wrong, instead of inventing placeholder text.
 */
export function getGrammarReviewPool(): Record<string, GrammarReviewEntry> {
  return Object.fromEntries(
    allGrammarRules.map((rule) => [
      rule.id,
      {
        title: rule.title,
        targetEnglish: rule.speakingPractice.targetEnglish,
        vietnameseHint: rule.speakingPractice.vietnameseHint,
      },
    ]),
  );
}
